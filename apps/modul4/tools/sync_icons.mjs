// Writes src/icons.js: the Phosphor (regular, MIT) paths the hunt uses,
// and no others. Paths come from the Phase 9 mockup's app/icons.js (which
// copied them from @phosphor-icons/core 2.1.1) and, for any name it lacks,
// from that package on unpkg. Run from apps/modul4 after adding an icon:
//   node tools/sync_icons.mjs <path to mockups/phase9/app/icons.js>
import fs from "node:fs";
import vm from "node:vm";

const from = process.argv[2];
const ctx = { window: {} };
if (from) vm.runInNewContext(fs.readFileSync(from, "utf8"), ctx);
const old = (() => {
  try {
    const c = { window: {} };
    vm.runInNewContext(fs.readFileSync("src/icons.js", "utf8"), c);
    return c.window.PH_ICONS || {};
  } catch {
    return {};
  }
})();
const PH = { ...old, ...(ctx.window.PH_ICONS || {}) };
let code = "";
for (const f of fs.readdirSync("src")) if (f.endsWith(".js") && f !== "icons.js") code += fs.readFileSync("src/" + f, "utf8");
const names = new Set(["x"]);
for (const m of code.matchAll(/(?:\bn|icon|iconEnd|\bi)[=:]\s*"([a-z0-9-]+)"/g)) names.add(m[1]);
for (const m of code.matchAll(/"([a-z0-9-]+)"/g)) if (PH[m[1]]) names.add(m[1]);
const out = {};
for (const n of [...names].sort()) {
  if (PH[n]) {
    out[n] = PH[n];
    continue;
  }
  const r = await fetch(`https://unpkg.com/@phosphor-icons/core@2.1.1/assets/regular/${n}.svg`);
  if (!r.ok) continue; // a word that only looked like an icon name
  const svg = await r.text();
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (d.length === 1) out[n] = d[0];
  else console.warn(`skipped ${n}: ${d.length} paths`);
}
fs.writeFileSync(
  "src/icons.js",
  "/* Phosphor Icons (regular, MIT), paths from @phosphor-icons/core 2.1.1.\n   Generated by tools/sync_icons.mjs: only the icons the hunt uses. */\n" +
    "window.PH_ICONS=" + JSON.stringify(out) + ";\n",
);
console.log(Object.keys(out).length, "icons");
