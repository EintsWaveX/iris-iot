// Writes src/style/mockup.css: the Phase 9 mockup's stylesheets (the
// source of truth for the look), cut down to the rules whose classes the
// hunt's own scripts use, with the mockup's device frame (.dev) renamed to
// the page root (.app). Re-run after the mockup changes or after a screen
// starts using a new class. Needs postcss, which apps/web already has:
//   node tools/prune_css.mjs <path to mockups/phase9/app>
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(new URL("../../web/package.json", import.meta.url));
const postcss = require("postcss");

const dir = process.argv[2];
if (!dir) throw new Error("usage: node tools/prune_css.mjs <mockups/phase9/app>");
const FILES = ["styles.css", "screens.css", "round3.css", "round4.css", "round5.css", "hunt.css"];
/* page chrome of the mockup itself, never part of the app */
const DENY = new Set(["pc", "notes", "stage", "frame-scale", "dev__label", "tag", "tagrow"]);

let code = "";
for (const f of fs.readdirSync("src")) if (f.endsWith(".js") && f !== "icons.js") code += fs.readFileSync(path.join("src", f), "utf8");
const words = new Set(code.match(/[A-Za-z][A-Za-z0-9_-]*/g));
["huntapp", "huntapp__scroll", "huntapp__layers", "layer", "ic", "ic--sm", "ic--lg"].forEach((w) => words.add(w));
/* class names the kit builds at run time, like "btn--" + kind */
for (const p of ["btn--", "iconbtn--", "badge--", "toast--", "banner--", "dot--", "hcell--", "hgrid--", "dcards--"]) for (const w of [...words]) words.add(p + w);
words.delete("app"); /* the mockup's inner shell class; the hunt has its own root */

const classesOf = (sel) => [...sel.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)].map((m) => m[1]);
const keepSelector = (sel) => {
  const c = classesOf(sel);
  return c.every((x) => words.has(x) && !DENY.has(x));
};

/* .huntapp, not .app: the mockup already has an inner .app shell class */
const rename = (s) => s.replace(/\.dev(?=[\s.:[,>+~)]|$)/g, ".huntapp").replace(/\.dev__/g, ".huntapp__");
const root = postcss.root();
for (const f of FILES) {
  const css = fs.readFileSync(path.join(dir, f), "utf8");
  const r = postcss.parse(css, { from: f });
  root.append(postcss.comment({ text: ` ---- ${f} ---- ` }));
  root.append(r.nodes);
}
root.walkAtRules("container", (a) => {
  a.params = a.params.replace(/^dev\b/, "huntapp");
});
root.walkDecls("container", (d) => {
  d.value = d.value.replace(/^dev\b/, "huntapp");
});
root.walkRules((rule) => {
  if (rule.parent && rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  const sels = rule.selectors.map(rename).filter(keepSelector);
  if (!sels.length) rule.remove();
  else rule.selectors = sels;
});
/* keyframes only when something kept still names them */
const used = new Set();
root.walkDecls(/^animation(-name)?$/, (d) => d.value.split(/[\s,]+/).forEach((w) => used.add(w)));
root.walkAtRules(/keyframes$/, (a) => {
  if (!used.has(a.params)) a.remove();
});
/* drop at-rules left empty, innermost first */
let again = true;
while (again) {
  again = false;
  root.walkAtRules((a) => {
    if (a.nodes && !a.nodes.some((n) => n.type !== "comment")) {
      a.remove();
      again = true;
    }
  });
}
root.walkComments((c) => {
  if (!c.text.startsWith("---- ")) c.remove();
});
const header =
  "/* GENERATED by tools/prune_css.mjs from the Phase 9 mockup's stylesheets.\n" +
  "   Do not edit here: change the mockup or src/style/app.css, then re-run. */\n";
let out = header + root.toString().replace(/\n{3,}/g, "\n\n");
/* the mockup frame's border, radius and shadow belong to the prototype */
fs.mkdirSync("src/style", { recursive: true });
fs.writeFileSync("src/style/mockup.css", out);
console.log("wrote src/style/mockup.css", Buffer.byteLength(out), "bytes");
