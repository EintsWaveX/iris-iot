/**
 * The default question bank (EXAM-ENGINE 3.1 and 10.4, prompt 09).
 *
 * The questions are written as Markdown in scripts/rec-bank/*.md (one file
 * per part, read in file name order), in the import format of bank-io.ts.
 * This script parses them all, checks every one with validateQuestion, checks
 * the default parts config can start on them, and writes the module the API
 * bundles (src/lib/recruitment/seed-bank.ts). Run it after any edit:
 *
 *   npx tsx scripts/rec-bank-seed.ts          write the module
 *   npx tsx scripts/rec-bank-seed.ts --check  fail if the module is out of date
 *   --allow-short                              while the bank is still being written
 *
 * Every question carries `sample: true` (only the "Bawaan" badge) and was run
 * or compiled before it went in; scripts/rec-bank-verify.py is how.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseBank } from "../src/lib/recruitment/bank-io.js";
import { DEFAULT_EXAM_CONFIG, PHASE1_PARTS } from "../src/lib/recruitment/exam-types.js";
import { poolCounts } from "../src/lib/recruitment/bank-rules.js";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, "rec-bank");
const OUT = join(here, "..", "src", "lib", "recruitment", "seed-bank.ts");

const files = readdirSync(SRC)
  .filter((f) => f.endsWith(".md"))
  .sort();
const md =
  files.map((f) => readFileSync(join(SRC, f), "utf8").replace(/\r\n/g, "\n").trim()).join("\n\n") +
  "\n";

const items = parseBank(md);
let bad = 0;
const seen = new Set<string>();
for (const it of items) {
  for (const e of it.errors) {
    console.error(
      `line ${e.line}: ${it.title || "(no title)"}: ${e.kode}${e.field ? ` (${e.field})` : ""}`,
    );
    bad++;
  }
  const d = it.draft;
  if (!d) continue;
  const k = `${d.part}|${d.lang}|${d.title}`;
  if (seen.has(k)) {
    console.error(`duplicate title in ${d.part}/${d.lang}: ${d.title}`);
    bad++;
  }
  seen.add(k);
  if (!d.sample) {
    console.error(`not marked sample: ${d.title}`);
    bad++;
  }
  if (d.status !== "ready") {
    console.error(`not ready: ${d.title}`);
    bad++;
  }
}
const drafts = items.flatMap((i) => (i.draft ? [i.draft] : []));
const pools = poolCounts(
  drafts.map((d) => ({
    part: d.part,
    lang: d.lang,
    status: d.status,
    sample: d.sample,
    voided: false,
  })),
  DEFAULT_EXAM_CONFIG,
);
for (const part of PHASE1_PARTS)
  for (const c of pools[part]) {
    console.log(
      `${part.padEnd(9)} ${c.lang.padEnd(4)} ${String(c.ready).padStart(3)} ready, a room needs ${c.shown}${c.missing ? `  SHORT by ${c.missing}` : ""}`,
    );
    if (c.missing && !process.argv.includes("--allow-short")) bad++;
  }
console.log(`${drafts.length} questions from ${files.length} files`);
if (bad) {
  console.error(`${bad} problem(s); nothing written`);
  process.exit(1);
}

const out = `/**
 * The default question bank, GENERATED by scripts/rec-bank-seed.ts from
 * scripts/rec-bank/*.md. Do not edit by hand; edit the Markdown and run it.
 */
export const SEED_MD = ${JSON.stringify(md)};
`;
if (process.argv.includes("--check")) {
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (now !== out) {
    console.error("seed-bank.ts is out of date; run: npx tsx scripts/rec-bank-seed.ts");
    process.exit(1);
  }
} else writeFileSync(OUT, out);
